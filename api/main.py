@app.post("/diagnosticos/{diagnostico_id}/enviar-email")
def enviar_diagnostico_por_email(diagnostico_id: int, payload: EmailRequest):
    diagnostico = get_diagnostico_by_id_db(diagnostico_id)

    if not diagnostico:
        raise HTTPException(status_code=404, detail="Diagnóstico não encontrado.")

    if "@" not in payload.email or "." not in payload.email:
        raise HTTPException(status_code=400, detail="E-mail inválido.")

    try:
        pdf_bytes = gerar_relatorio_pdf(diagnostico)

        lang = payload.idioma or diagnostico.get("idioma", "pt") or "pt"
        email_text = EMAIL_TEXTS_BY_LANG.get(lang, EMAIL_TEXTS_BY_LANG["pt"])

        moeda = payload.moeda or diagnostico.get("moeda", "BRL") or "BRL"
        simbolo_moeda = payload.simbolo_moeda or diagnostico.get("simbolo_moeda", "R$") or "R$"

        nome = diagnostico.get("nome", "usuário")
        saldo = (
            diagnostico.get("saldo_estimado")
            or diagnostico.get("saldo_mensal_estimado")
            or diagnostico.get("saldo_mensal")
            or diagnostico.get("saldo")
            or 0
        )
        saldo_formatado = format_money_by_currency(saldo, simbolo_moeda, moeda)

        risco_original = diagnostico.get("nivel_risco", diagnostico.get("risco", "não informado"))
        risco = translate_risk_level(risco_original, lang)

        subject = email_text["subject"]

        body = f"""{email_text["hello"]}, {nome}.

{email_text["intro"]}

{email_text["summary"]}
- {email_text["balance"]}: {saldo_formatado}
- {email_text["risk"]}: {risco}

{email_text["about"]}

{email_text["channels"]}

{email_text["bye"]}
INNA Financial Coach AI
"""

        send_diagnostico_email(
            to_email=payload.email,
            subject=subject,
            body=body,
            pdf_bytes=pdf_bytes,
            filename=f"relatorio-inna-{diagnostico_id}.pdf",
        )

        return {
            "success": True,
            "message": "Relatório enviado por e-mail com sucesso.",
            "email": payload.email,
            "diagnostico_id": diagnostico_id,
            "idioma": lang,
            "moeda": moeda,
        }

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Erro ao enviar e-mail: {str(exc)}",
        )
