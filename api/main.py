def _load_llamaindex_agentic_rag_runtime():
    """Lazy-load LlamaIndex while preserving the legacy path."""
    from src.services import llamaindex_agentic_rag

    return llamaindex_agentic_rag


def _execute_rag_ask_runtime(
    payload: RagAskRequest,
) -> dict:
    """Select LlamaIndex or preserve the existing RAG runtime."""
    runtime = _load_llamaindex_agentic_rag_runtime()

    if not runtime.llamaindex_agentic_rag_enabled():
        return answer_with_rag(
            pergunta=payload.pergunta,
            idioma=payload.idioma,
            top_k=payload.top_k,
        )

    normalized_language = (
        str(payload.idioma or "pt")
        .strip()
        .lower()
        .replace("_", "-")
    )

    if not normalized_language.startswith("pt"):
        return answer_with_rag(
            pergunta=payload.pergunta,
            idioma=payload.idioma,
            top_k=payload.top_k,
        )

    try:
        import asyncio

        result = asyncio.run(
            runtime.executar_llamaindex_agent_workflow_payload(
                payload.pergunta,
                idioma=payload.idioma,
                top_k=payload.top_k,
            )
        )

        if not isinstance(result, dict):
            raise RuntimeError("LlamaIndex retornou payload invalido.")

        return result

    except Exception as exc:
        fallback = answer_with_rag(
            pergunta=payload.pergunta,
            idioma=payload.idioma,
            top_k=payload.top_k,
        )

        if isinstance(fallback, dict):
            fallback = dict(fallback)
            fallback["llamaindex_agentic_rag"] = {
                "enabled": True,
                "executed": False,
                "fallback_used": True,
                "runtime": "agent_workflow",
                "error_type": type(exc).__name__,
            }

        return fallback


@app.post("/rag/ask")
def rag_ask(
    payload: RagAskRequest,
    background_tasks: BackgroundTasks,
):
    """
    Responde usando RAG e expõe telemetria de latência
    operacional sem alterar o comportamento funcional.
    """
    try:
        import time

        endpoint_started = time.perf_counter()

        rag_started = time.perf_counter()

        result = _execute_rag_ask_runtime(
            payload
        )

        answer_with_rag_ms = round(
            (time.perf_counter() - rag_started) * 1000
        )

        # Nome correto para o gateway atual. Mantemos
        # answer_with_rag_ms abaixo por compatibilidade.
        rag_runtime_ms = answer_with_rag_ms

        retrieval_trace = (
            result.get("retrieval_trace")
            if isinstance(result, dict)
            else None
        ) or {}

        retrieval_trace_ms = retrieval_trace.get(
            "total_time_ms"
        )

        if retrieval_trace_ms is not None:
            try:
                retrieval_trace_ms = int(
                    retrieval_trace_ms
                )
            except (TypeError, ValueError):
                retrieval_trace_ms = None

        post_retrieval_inside_rag_ms = None

        if retrieval_trace_ms is not None:
            post_retrieval_inside_rag_ms = max(
                0,
                answer_with_rag_ms - retrieval_trace_ms,
            )

        background_schedule_started = (
            time.perf_counter()
        )

        background_tasks.add_task(
            save_rag_log,
            pergunta=payload.pergunta,
            resultado=result,
            tempo_resposta_ms=answer_with_rag_ms,
        )

        background_tasks.add_task(
            safe_record_event,
            canal="rag",
            usuario="admin",
            idioma=payload.idioma,
            moeda="BRL",
            status="success",
            pergunta=payload.pergunta,
            resposta=result.get("resposta"),
            metadata={
                "evento": "rag_ask",
                "origem": "api",
                "modo": result.get("modo"),
                "trace_id": result.get("trace_id"),
                "retrieval_trace": result.get(
                    "retrieval_trace"
                ),
                "fontes": result.get("fontes", []),
            },
        )

        background_telemetry_schedule_ms = round(
            (
                time.perf_counter()
                - background_schedule_started
            )
            * 1000
        )

        endpoint_processing_ms = round(
            (time.perf_counter() - endpoint_started)
            * 1000
        )

        if isinstance(result, dict):
            result["api_latency"] = {
                "retrieval_trace_ms": (
                    retrieval_trace_ms
                ),
                "rag_runtime_ms": (
                    rag_runtime_ms
                ),
                "answer_with_rag_ms": (
                    answer_with_rag_ms
                ),
                "post_retrieval_inside_rag_ms": (
                    post_retrieval_inside_rag_ms
                ),
                "save_rag_log_ms": None,
                "safe_record_event_ms": None,
                "telemetry_execution_mode": (
                    "background"
                ),
                "background_telemetry_scheduled": True,
                "background_telemetry_schedule_ms": (
                    background_telemetry_schedule_ms
                ),
                "endpoint_processing_ms": (
                    endpoint_processing_ms
                ),
            }

        return result

    except Exception as exc:
        safe_record_event(
            canal="rag",
            usuario="admin",
            idioma=payload.idioma,
            moeda="BRL",
            status="error",
            pergunta=payload.pergunta,
            resposta="Erro no RAG",
            metadata={
                "evento": "erro_rag_ask",
                "origem": "api",
                "erro": str(exc),
            },
        )

        raise HTTPException(
            status_code=500,
            detail=str(exc),
        ) from exc

